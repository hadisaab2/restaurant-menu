export const t = (key, lang = "en", replacements = {}) => {
  let str = (i18n[lang] && i18n[lang][key]) || key;
  if (replacements) {
    Object.entries(replacements).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, v);
    });
  }
  return str;
};

